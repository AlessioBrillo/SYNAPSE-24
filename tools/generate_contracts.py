#!/usr/bin/env python3
"""Generate the contract artifacts from the single source of truth.

The source of truth is ``config/hardware.yaml`` (UUIDs, rates, stream ids)
plus ``contracts/fit_developer_fields.json`` (the FIT developer fields).
Two artifacts are generated from it and **committed**:

* ``firmware/esp32_band/ble/synapse_contract_generated.h`` — the UUIDs, the
  stream ids and the rates as C constants, so the firmware cannot carry a
  second copy of the contract;
* ``src/synapse24/contracts_generated.py`` — the same values as Python
  constants, for the host and the tooling.

``--check`` regenerates in memory and fails when the committed files differ:
that is the drift gate, and it runs in CI.

Usage:
    uv run python tools/generate_contracts.py           # write the artifacts
    uv run python tools/generate_contracts.py --check   # fail on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "config" / "hardware.yaml"
FIT_DESCRIPTOR = ROOT / "contracts" / "fit_developer_fields.json"
C_HEADER = ROOT / "firmware" / "esp32_band" / "ble" / "synapse_contract_generated.h"
PY_MODULE = ROOT / "src" / "synapse24" / "contracts_generated.py"

BANNER = (
    "Generated by tools/generate_contracts.py from config/hardware.yaml and\n"
    "contracts/fit_developer_fields.json. Do not edit: run\n"
    "    uv run python tools/generate_contracts.py"
)


def _uuid_to_le_bytes(uuid: str) -> list[int]:
    """Return the 16 bytes of a UUID in NimBLE's ``BLE_UUID128_INIT`` order.

    NimBLE stores a 128-bit UUID little-endian: the first byte of the macro
    is the LAST byte of the canonical string.
    """
    raw = bytes.fromhex(uuid.replace("-", ""))
    return list(reversed(raw))


def _load_manifest() -> dict[str, Any]:
    with MANIFEST.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle) or {}


def _contract_values() -> dict[str, Any]:
    """Collect the contract values that both artifacts expose."""
    manifest = _load_manifest()
    pods = manifest.get("pods") or []
    if not pods:
        raise SystemExit(f"{MANIFEST}: no pods declared")
    pod = next((p for p in pods if p.get("pod_id") == "forearm_hub"), pods[0])

    ble = manifest.get("ble") or {}
    feature = ble.get("feature_stream") or {}
    pod_meta = pod.get("metadata") or {}
    research_chars = pod_meta.get("research_characteristics") or {}
    if not research_chars:
        raise SystemExit(f"{MANIFEST}: no metadata.research_characteristics declared")

    raw_frame = manifest.get("raw_frame") or {}
    stream_ids = raw_frame.get("stream_ids") or {}
    if not stream_ids:
        raise SystemExit(f"{MANIFEST}: no raw_frame.stream_ids declared")

    rates = pod.get("sampling_rate") or {}

    uuids: dict[str, str] = {
        "RESEARCH_SERVICE": str(pod_meta.get("research_service_uuid", "")).lower(),
        "CONSUMER_SERVICE": str(feature.get("service_uuid", "")).lower(),
        "CONSUMER_FEATURE": str(feature.get("characteristic_uuid", "")).lower(),
        "CONSUMER_DEVICE_CONFIG": str(feature.get("device_config_uuid", "")).lower(),
        "CONSUMER_PROVISIONING": str(feature.get("provisioning_uuid", "")).lower(),
    }
    for name, value in research_chars.items():
        uuids[f"RESEARCH_CHAR_{name.upper()}"] = str(value).lower()

    missing = [name for name, value in uuids.items() if not value]
    if missing:
        raise SystemExit(f"{MANIFEST}: empty UUIDs for {missing}")

    with FIT_DESCRIPTOR.open(encoding="utf-8") as handle:
        fit_fields = json.load(handle)["fields"]

    return {
        "uuids": uuids,
        "stream_ids": {str(k): int(v) for k, v in stream_ids.items()},
        "rates": {str(k): int(v) for k, v in rates.items()},
        "fit_fields": [(str(f["name"]), int(f["id"])) for f in fit_fields],
    }


def _render_c(values: dict[str, Any]) -> str:
    lines = [
        "/*",
        " * " + BANNER.replace("\n", "\n * "),
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "/* 128-bit UUIDs, in NimBLE's BLE_UUID128_INIT order (little-endian).",
        " *",
        " * Two forms per UUID:",
        " *   _INIT  a full BLE_UUID128_INIT(...) call, ready to use as",
        " *         `static const ble_uuid128_t X = SYNAPSE_CONTRACT_UUID_X_INIT;`",
        " *   _BYTES the raw byte list, for brace initialisers",
        " *         `{SYNAPSE_CONTRACT_UUID_X_BYTES}`.",
        " *",
        " * The header does not include NimBLE: the macros are only expanded",
        " * where they are used, in a translation unit that already has it. */",
    ]
    for name, uuid in sorted(values["uuids"].items()):
        raw = _uuid_to_le_bytes(uuid)
        chunks = ", ".join(f"0x{b:02X}" for b in raw)
        lines.append(f"#define SYNAPSE_CONTRACT_UUID_{name}_INIT \\")
        lines.append(f"    BLE_UUID128_INIT({chunks})")
        lines.append(f"#define SYNAPSE_CONTRACT_UUID_{name}_BYTES \\")
        lines.append(f"    {chunks}")
        lines.append(f'#define SYNAPSE_CONTRACT_UUID_{name}_STR "{uuid}"')
    lines += ["", "/* Raw frame stream ids (config/hardware.yaml raw_frame.stream_ids). */"]
    for name, value in sorted(values["stream_ids"].items()):
        lines.append(f"#define SYNAPSE_CONTRACT_STREAM_{name.upper()} 0x{value:02X}")
    lines += ["", "/* Normative sample rates (Hz). */"]
    for name, value in sorted(values["rates"].items()):
        lines.append(f"#define SYNAPSE_CONTRACT_RATE_{name.upper()}_HZ {value}")
    lines += ["", ""]
    return "\n".join(lines)


def _render_python(values: dict[str, Any]) -> str:
    lines = [
        '"""Contract constants generated from the single source of truth.',
        "",
        BANNER,
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "__all__ = [",
        '    "FIT_DEV_FIELDS",',
        '    "STREAM_IDS",',
        '    "STREAM_RATES_HZ",',
        '    "UUIDS",',
        "]",
        "",
        "#: 128-bit UUIDs of the GATT contract (canonical string form).",
        "UUIDS: dict[str, str] = {",
    ]
    for name, uuid in sorted(values["uuids"].items()):
        lines.append(f'    "{name}": "{uuid}",')
    lines += [
        "}",
        "",
        "#: Raw frame stream ids.",
        "STREAM_IDS: dict[str, int] = {",
    ]
    for name, value in sorted(values["stream_ids"].items()):
        lines.append(f'    "{name}": 0x{value:02X},')
    lines += [
        "}",
        "",
        "#: Normative sample rates (Hz).",
        "STREAM_RATES_HZ: dict[str, int] = {",
    ]
    for name, value in sorted(values["rates"].items()):
        lines.append(f'    "{name}": {value},')
    lines += [
        "}",
        "",
        "#: FIT developer fields: (name, contract id).",
        "FIT_DEV_FIELDS: tuple[tuple[str, int], ...] = (",
    ]
    for name, value in values["fit_fields"]:
        lines.append(f'    ("{name}", {value}),')
    lines += [
        ")",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed artifacts differ from the source of truth",
    )
    args = parser.parse_args(argv)

    values = _contract_values()
    artifacts = {C_HEADER: _render_c(values), PY_MODULE: _render_python(values)}

    if args.check:
        drift: list[str] = []
        for path, content in artifacts.items():
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != content:
                try:
                    drift.append(str(path.relative_to(ROOT)))
                except ValueError:  # outside the repository (tests)
                    drift.append(str(path))
        if drift:
            print("CONTRACT DRIFT: the generated artifacts are stale:", file=sys.stderr)
            for path in drift:
                print(f"  - {path}", file=sys.stderr)
            print(
                "Run: uv run python tools/generate_contracts.py",
                file=sys.stderr,
            )
            return 1
        print("CONTRACT ARTIFACTS OK")
        return 0

    for path, content in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        try:
            shown = path.relative_to(ROOT)
        except ValueError:  # outside the repository (tests)
            shown = path
        print(f"wrote {shown}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
