"""LabRecorderCLI harness: continuous XDF recording without reinventing it.

The dataset is the project's asset, and the recorder is the one component
where "reinvent it ourselves" is strictly negative value: LabRecorder/libRAISE
is the ecosystem standard, streams incrementally (a 6-hour soak must not sit
in memory), survives crashes, and writes XDF that MNE, pyxdf and every LSL
tool already read. This module does the three things the SOP needs:

* **find** the CLI (env-var override, then the usual install locations),
* **generate** a config file pinning the streams to record,
* **spawn/stop** it as a context manager, so a failure to start is an error
  with a recovery hint and never a silent "recorded nothing".

Post-hoc integrity (zero dropped samples, monotonic timestamps) stays with
``synapse24.utils.validate_xdf`` — the recorder is trusted for *writing*,
never for *proving*.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any

__all__ = [
    "CLI_ENV_VAR",
    "LabRecorderError",
    "LabRecorderNotFoundError",
    "find_labrecorder_cli",
    "generate_config",
    "record_session",
    "write_session_metadata",
]

CLI_ENV_VAR = "SYNAPSE_LABRECORDER_CLI"

# Where the CLI installs itself, per platform. An env var wins over all of
# these so a CI runner or a portable checkout can point anywhere.
_CANDIDATE_PATHS = (
    Path("C:/Program Files/LabRecorder/LabRecorderCLI.exe"),
    Path("C:/Program Files (x86)/LabRecorder/LabRecorderCLI.exe"),
    Path("/usr/local/bin/LabRecorderCLI"),
    Path("/usr/bin/LabRecorderCLI"),
    Path("/opt/homebrew/bin/LabRecorderCLI"),
)


class LabRecorderError(RuntimeError):
    """Base error for recorder problems; carries a recovery hint."""

    recovery_hint = "See docs/hardware/BRINGUP_SOP.md."


class LabRecorderNotFoundError(LabRecorderError):
    """The CLI could not be located."""

    recovery_hint = (
        f"Install LabRecorder (https://github.com/labstreaminglayer/App-LabRecorder) "
        f"and set {CLI_ENV_VAR} to the LabRecorderCLI executable, or record with any "
        f"LSL recorder that writes XDF and validate the file with "
        f"synapse24.utils.validate_xdf."
    )


def find_labrecorder_cli() -> Path | None:
    """Locate the LabRecorderCLI executable, or None if absent."""
    override = os.environ.get(CLI_ENV_VAR)
    if override:
        path = Path(override)
        return path if path.exists() else None

    on_path = shutil.which("LabRecorderCLI") or shutil.which("LabRecorderCLI.exe")
    if on_path:
        return Path(on_path)

    for candidate in _CANDIDATE_PATHS:
        if candidate.exists():
            return candidate
    return None


def generate_config(
    stream_specs: list[dict[str, Any]],
    output_path: Path,
    *,
    record_all: bool = False,
) -> Path:
    """Write a LabRecorderCLI config pinning the streams to record.

    Args:
        stream_specs: Stream descriptors with ``name`` and optional ``uid``
            (the LSL source_id). Names are matched by LabRecorder's stream
            selector syntax.
        output_path: Where to write the config file.
        record_all: When True, record every stream on the network (used for
            the soak, where marker/power streams come and go).

    Returns:
        The path of the written config file.
    """
    lines = [
        "# Generated by SYNAPSE-24 — do not edit by hand.",
        "# LabRecorderCLI configuration; see docs/hardware/PROCUREMENT.md.",
        "",
        "[Config]",
        "Session = SYNAPSE-24",
        "Blocks = 1",
        "Study = SYNAPSE-24",
        "Experimenter = solo-researcher",
        "PathTemplate = Recordings/S {BlockName}/eeg.xdf",
        "TaskName = acquisition",
        "FilenamePrefix = synapse_",
    ]
    if record_all or not stream_specs:
        lines += ["[SelectAll]", "1"]
    else:
        for spec in stream_specs:
            name = str(spec.get("name", "")).strip()
            if not name:
                continue
            lines += ["[Stream]", f"Name = {name}"]
            uid = str(spec.get("uid", "")).strip()
            if uid:
                lines.append(f"UID = {uid}")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output_path


def write_session_metadata(path: Path, metadata: dict[str, Any]) -> None:
    """Write the provenance manifest that travels with the recording."""
    import json

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(metadata, indent=2, default=str), encoding="utf-8")


@dataclass
class RecordedSession:
    """Handle to a running recording."""

    process: subprocess.Popen
    config_path: Path
    record_dir: Path


@contextmanager
def record_session(
    record_dir: Path,
    stream_specs: list[dict[str, Any]] | None = None,
    *,
    record_all: bool = False,
    config_name: str = "synapse_recording.cfg",
) -> Iterator[RecordedSession]:
    """Record every selected LSL stream to XDF for the duration of the block.

    Raises:
        LabRecorderNotFoundError: If the CLI is not installed or not on the
            configured path. Starting a session that writes nothing is worse
            than failing loudly here.
    """
    cli = find_labrecorder_cli()
    if cli is None:
        raise LabRecorderNotFoundError(
            "LabRecorderCLI was not found; cannot start the continuous XDF recording."
        )

    record_dir.mkdir(parents=True, exist_ok=True)
    config_path = generate_config(
        stream_specs or [], record_dir / config_name, record_all=record_all
    )
    process = subprocess.Popen(  # noqa: S603 - path comes from an explicit lookup
        [str(cli), "-c", str(config_path), "-r", str(record_dir)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    session = RecordedSession(process=process, config_path=config_path, record_dir=record_dir)
    try:
        yield session
    finally:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
        write_session_metadata(
            record_dir / "session_meta.json",
            {
                "config_path": str(config_path),
                "record_dir": str(record_dir),
                "recorder": str(cli),
                "returncode": process.returncode,
            },
        )
